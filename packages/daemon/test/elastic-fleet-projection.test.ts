it('atomically fences reserve/delivery/retry by eligibility revision, drain, incarnation, config, approval scope and credential expiry', () => {
    const f = fixture();
    const target = f.projection.targets()[0]!;
    const auth = (phase: 'reserve' | 'delivery' | 'retry', id = 'qitem-reserved', cap = 'github:1:public-read') => f.db.transaction(() => f.projection.authorize(target, f.issue, cap, id, phase))();
    expect(() => f.projection.authorize(target, f.issue, 'github:1:public-read', 'qitem-x', 'reserve')).toThrow('transaction');
    auth('reserve');
    auth('delivery');
    f.setNow(11000);
    f.projection.publish(f.attempt, f.observation());
    expect(() => auth('delivery')).toThrow('revision_changed');
    auth('retry');
    auth('delivery');
    const busy = f.observation();
    busy.worker.state = 'draining';
    f.projection.publish(f.attempt, busy);
    expect(() => auth('retry')).toThrow('ineligible');
    f.projection.publish(f.attempt, f.observation());
    expect(() => auth('reserve', 'qitem-private', 'github:1:private-read')).toThrow('ineligible');
    expect(() => auth('reserve', 'qitem-write', 'github:1:write')).toThrow('ineligible');
    const replacement = { ...f.attempt, binding: { ...f.attempt.binding, vmId: '22222222-2222-4222-8222-222222222222' } };
    const changed = f.observation();
    changed.probe!.state.vmId = replacement.binding.vmId;
    f.projection.publish(replacement, changed);
    expect(() => auth('retry')).toThrow('identity_changed');
    f.projection.publish(f.attempt, f.observation());
    f.db.prepare('UPDATE elastic_fleet_config SET revision=revision+1').run();
    expect(() => auth('retry')).toThrow('ineligible');
    f.projection.publish({ ...f.attempt, credential: { revision: 'expired', expiresAt: 11000 } }, f.observation());
    expect(() => auth('retry')).toThrow('ineligible');
});
it('dispatches distinct native work to free B while A owns ongoing work; uncertain create retains exact qitem and manual config', async () => {
    const f = fixture();
    const artifactRoot = mkdtempSync(join(tmpdir(), 'elastic-overlap-'));
    const actor = spawn(process.execPath, ['-e', "process.stdout.write('working\\n');setInterval(()=>{},1000)"], { stdio: ['ignore', 'pipe', 'pipe'] });
    await once(actor.stdout, 'data');
    try {
        const ongoing = await f.queue.create({ qitemId: 'qitem-ongoing-a', sourceSession: 'manager@coordinator', destinationSession: 'worker-a@elastic', body: 'Ongoing work', nudge: false });
        f.queue.claim({ qitemId: ongoing.qitemId, destinationSession: 'worker-a@elastic' });
        const active = f.observation();
        active.worker.active = 1;
        active.probe!.preparation.seats[0]!.active = true;
        active.probe!.process.complete = false;
        active.probe!.ledger.clean = false;
        active.drainEligible = false;
        f.projection.publish(f.attempt, active);
        await f.service.reconcile();
        f.service.markEligibility({ repositoryId: '1', number: 1, revision: f.issue.updatedAt, eligibility: 'ready', capability: 'github:1:public-read', reason: 'Reviewed owner/repository/capability' });
        await f.service.reconcile();
        const assigned = f.service.status().issues[0]!;
        expect(assigned.session).toBe('worker-b@elastic');
        expect(f.service.status().config?.targets).toEqual([]);
        expect(f.io.createTask).toHaveBeenCalledTimes(1);
        f.queue.claim({ qitemId: assigned.qitemId!, destinationSession: 'worker-b@elastic' });
        expect(f.queue.getById(ongoing.qitemId)?.claimedAt).toBeTruthy();
        expect(f.queue.getById(assigned.qitemId!)?.claimedAt).toBeTruthy();
        execFileSync(process.execPath, ['-e', "require('fs').writeFileSync(process.argv[1],JSON.stringify({qitemId:process.argv[2],seat:'worker-b@elastic'}))", join(artifactRoot, 'proof.json'), assigned.qitemId!]);
        expect(JSON.parse(readFileSync(join(artifactRoot, 'proof.json'), 'utf8'))).toEqual({ qitemId: assigned.qitemId, seat: 'worker-b@elastic' });
        expect(() => process.kill(actor.pid!, 0)).not.toThrow();
        f.queue.update({ qitemId: assigned.qitemId!, actorSession: 'worker-b@elastic', state: 'done', closureReason: 'no-follow-on', resolution: 'Independent native fixture artifact written' });
        expect(f.queue.getById(ongoing.qitemId)?.state).toBe('in-progress');
        const original = f.io.createTask;
        f.io.getTask = async () => { throw Error('unavailable'); };
        await f.service.reconcile();
        expect(f.io.createTask).toHaveBeenCalledTimes(1);
        expect(f.service.status().issues[0]!.qitemId).toBe(assigned.qitemId);
        void original;
    }
    finally {
        const exited = once(actor, 'exit');
        actor.kill('SIGTERM');
        await exited;
        rmSync(artifactRoot, { recursive: true, force: true });
    }
});
it('resets idle continuity on busy/unknown/gaps/restart/custody/identity and never ages a duplicate sample', () => {
    const f = fixture();
    const sample = () => f.observation();
    expect(f.projection.idleSince(f.attempt, sample(), 5000)).toBe(10000);
    f.setNow(14000);
    const duplicate = sample();
    duplicate.probe!.observedAt = 10000;
    expect(f.projection.idleSince(f.attempt, duplicate, 5000)).toBeNull();
    f.setNow(15000);
    expect(f.projection.idleSince(f.attempt, sample(), 5000)).toBe(10000);
    f.setNow(22000);
    expect(f.projection.idleSince(f.attempt, sample(), 5000)).toBe(22000);
    expect(new ElasticFleetProjection(f.db, f.now).idleSince(f.attempt, sample(), 5000)).toBe(22000);
    f.setNow(23000);
    const changed = sample();
    changed.probe!.ledger.digest = 'd'.repeat(64);
    expect(f.projection.idleSince(f.attempt, changed, 5000)).toBe(23000);
    const busy = sample();
    busy.worker.active = 1;
    expect(f.projection.idleSince(f.attempt, busy, 5000)).toBeNull();
    expect(f.projection.idleSince(f.attempt, { ...sample(), probe: null }, 5000)).toBeNull();
});
