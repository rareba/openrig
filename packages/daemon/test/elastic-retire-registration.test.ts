import { afterEach, expect, it } from 'vitest';
import { chmodSync, mkdtempSync, realpathSync, rmSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { ElasticWorkerAttemptStore } from '../src/adapters/elastic-worker-attempts.js';
import { managedHostId } from '../src/adapters/elastic-worker-enrollment.js';
import { retireElasticRegistration } from '../src/adapters/elastic-retire-registration.js';
import { addHostEntry } from '../src/domain/hosts/hosts-registry-writer.js';
import { loadHostRegistry } from '../src/domain/hosts/hosts-registry-reader.js';
const roots: string[] = [];
afterEach(() => roots.splice(0).forEach(path => rmSync(path, { recursive: true, force: true })));
it('retires only the exact original registration and retains private historical key and bearer', () => {
    const root = realpathSync(mkdtempSync(join(tmpdir(), 'elastic-retire-')));
    roots.push(root);
    chmodSync(root, 0o700);
    const store = new ElasticWorkerAttemptStore(root);
    const resourceId = '/fixture';
    let attempt = store.createOrRead({ resourceId, childResourceId: resourceId + '/virtualMachines/0', instanceId: '0', vmId: '11111111-1111-4111-8111-111111111111', operationId: 'original', fleetEpoch: 'epoch', manifestDigest: 'a'.repeat(64), artifactDigest: 'b'.repeat(64), specDigest: 'c'.repeat(64), checkoutDigest: 'd'.repeat(64), configurationDigest: 'e'.repeat(64) });
    store.saveBearer(attempt.id, 'fixture-worker-bearer-'.repeat(3));
    const id = managedHostId(attempt.workerId);
    attempt = store.advance(attempt.id, attempt.revision, { registration: { hostId: id, baseUrl: 'http://10.0.0.2:17433', selfHostId: 'native-worker' } });
    const path = join(root, 'hosts.yaml');
    expect(addHostEntry({ id: 'manual', transport: 'http', url: 'http://10.0.0.3:17433' }, path).ok).toBe(true);
    expect(addHostEntry({ id, transport: 'http', hostId: 'native-worker', url: 'http://10.0.0.2:17433', bearer_file: store.tokenPath(attempt.id) }, path).ok).toBe(true);
    const original = readFileSync(path, 'utf8');
    writeFileSync(path, original.replace('native-worker', 'changed-worker'));
    expect(() => retireElasticRegistration(store, attempt, path)).toThrow('elastic_registration_changed');
    expect(readFileSync(path, 'utf8')).toContain('changed-worker');
    writeFileSync(path, original);
    retireElasticRegistration(store, attempt, path);
    retireElasticRegistration(store, attempt, path);
    const registry = loadHostRegistry(path);
    expect(registry.ok && registry.registry.hosts.map(h => h.id)).toEqual(['manual']);
    expect(existsSync(store.tokenPath(attempt.id))).toBe(true);
    expect(store.read(attempt.id).keyDigest).toBe(attempt.keyDigest);
    expect(store.readPrivateInput(attempt.id, 'registration-retired')).toEqual({ registration: attempt.registration });
});
